"""Regenerate results/RESULTS.md from every run manifest, so the table can never drift from the runs."""

import json
from pathlib import Path

RUNS_DIR = Path("results/runs")
RESULTS_MD = Path("results/RESULTS.md")

HEADER = """# Results

Generated by `scripts/make_results_table.py` from `results/runs/*/manifest.json`. Do not edit by hand.

**EX** (execution accuracy): the gold and the predicted SQL run on the same database. Their rows are
compared as multisets, or as ordered lists when the gold query has a top-level `ORDER BY`, and the
columns must come in the gold's order. A prediction that errors or times out is wrong. So is an example
whose gold query fails, times out or returns more rows than the run's cap (`exec.max_rows` in the
manifest). **EX (valid gold)** leaves those examples out. **EX (any col. order)** also accepts the
prediction's columns in another order, as Spider's official evaluator does; it shows what the strict
column rule costs. Neither official evaluator computes exactly EX: BIRD's compares sets of rows (ADR-013
in `docs/DECISIONS.md`). If `n` is smaller than the split, the run used a stratified sample (`--limit`,
seed in the manifest).
"""


def load_manifests(runs_dir: Path = RUNS_DIR) -> list[dict]:
    manifests = [json.loads(p.read_text(encoding="utf-8")) for p in runs_dir.glob("*/manifest.json")]
    return sorted(manifests, key=lambda m: (m["dataset"], m["split"], m["started_at"]))


def pct(value: float | None) -> str:
    return "–" if value is None else f"{100 * value:.1f}"


def model_row(m: dict) -> str:
    config = m["config"]
    metrics = m["metrics"]
    cells = [
        m["started_at"][:10],
        f"{m['dataset']} {m['split']}",
        f"{m['n']}/{m['n_split']}",
        f"`{m['model']}`",
        m["quantization"] or "–",
        "on" if config["linking"]["enabled"] else "off",
        str(config["repair"]["max_repairs"]),
        f"**{pct(metrics['ex'])}**",
        pct(metrics["ex_valid_gold"]),
        pct(metrics.get("ex_any_column_order")),  # added after the first runs; missing from their manifests
        f"{metrics['p50_latency_ms']:.0f}" if metrics["p50_latency_ms"] is not None else "–",
        f"`{m['run_id']}`",
    ]
    return "| " + " | ".join(cells) + " |"


def gold_row(m: dict) -> str:
    cells = [
        m["started_at"][:10],
        f"{m['dataset']} {m['split']}",
        f"{m['n']}/{m['n_split']}",
        pct(m["metrics"]["ex"]),
        pct(m["metrics"]["ex_valid_gold"]),
        str(m["counts"]["gold_errors"]),
        f"`{m['run_id']}`",
    ]
    return "| " + " | ".join(cells) + " |"


def render(manifests: list[dict]) -> str:
    model_runs = [m for m in manifests if m["mode"] == "model"]
    gold_runs = [m for m in manifests if m["mode"] == "gold_passthrough"]
    lines = [HEADER, "## Model runs", ""]
    lines += [
        "| Date | Data | n | Model | Quant | Linking | Repairs | EX | EX (valid gold) | EX (any col. order) "
        "| p50 ms | Run |",
        "|---|---|---|---|---|---|---|---|---|---|---|---|",
        *map(model_row, model_runs),
    ]
    lines += ["", "## Harness sanity check: gold SQL scored as the prediction", ""]
    lines += [
        "Should be 100% on valid gold; anything less is an evaluator bug.",
        "",
        "| Date | Data | n | EX | EX (valid gold) | Broken gold | Run |",
        "|---|---|---|---|---|---|---|",
        *map(gold_row, gold_runs),
    ]
    return "\n".join(lines) + "\n"


def write_results(runs_dir: Path = RUNS_DIR, out: Path = RESULTS_MD) -> Path:
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(render(load_manifests(runs_dir)), encoding="utf-8")
    return out
